#!/usr/bin/env python3
"""Regenerate the KEYS table in src/session/vial/zmk_keys.rs from a ZMK checkout.

    python3 scripts/zmk_keys.py ~/zmk/app/include/dt-bindings/zmk

Every `#define` in keys.h becomes one (name, value) entry, in header order,
aliases included. Values are what the preprocessor would produce:
`(mods << 24) | (page << 16) | id`, with modifier wrappers such as `LS(...)`
applied. Only the text between `// BEGIN GENERATED` and `// END GENERATED` is
rewritten; the hand-written code around it is kept.
"""

import re
import subprocess
import sys
from pathlib import Path

zmk = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/zmkk/app/include/dt-bindings/zmk")
out = Path(__file__).resolve().parent.parent / "src/session/vial/zmk_keys.rs"


def defines(name):
    """Object-like `#define NAME body` pairs, continuation lines joined and comments dropped."""
    text = (zmk / name).read_text().replace("\\\n", " ")
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    return re.findall(r"^#define (\w+)[ \t]+(.+?)\s*$", text, re.M)


class Scope(dict):
    """Macro names resolved on first use, so bodies may refer to later or other-header defines."""

    def __init__(self, bodies):
        super().__init__()
        self.bodies = bodies

    def __missing__(self, name):
        value = self[name] = eval(self.bodies[name], {"__builtins__": {}}, self)
        return value


keys = defines("keys.h")
bodies = {}
for header in ("hid_usage_pages.h", "hid_usage.h", "modifiers.h", "keys.h"):
    bodies.update(defines(header))
scope = Scope(bodies)
scope["ZMK_HID_USAGE"] = lambda page, id: page << 16 | id
scope["APPLY_MODS"] = lambda mods, keycode: mods << 24 | keycode
for fn, mod in [("LC", 0x01), ("LS", 0x02), ("LA", 0x04), ("LG", 0x08),
                ("RC", 0x10), ("RS", 0x20), ("RA", 0x40), ("RG", 0x80)]:
    scope[fn] = lambda keycode, mod=mod: mod << 24 | keycode

try:
    commit = subprocess.run(["git", "-C", zmk, "rev-parse", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()
except (OSError, subprocess.CalledProcessError):
    commit = "main"

rows = "".join(f'    ("{name}", 0x{scope[name] >> 16:04X}_{scope[name] & 0xFFFF:04X}),\n' for name, _ in keys)
table = (
    f"// Generated by scripts/zmk_keys.py from zmkfirmware/zmk@{commit}. Do not edit by hand.\n"
    "/// Every name keys.h defines, in header order, with its value\n"
    "/// `(mods << 24) | (page << 16) | id`.\n"
    "pub(super) const KEYS: &[(&str, u32)] = &[\n"
    f"{rows}];\n"
)

source = out.read_text()
head, rest = source.split("// BEGIN GENERATED\n", 1)
_, tail = rest.split("// END GENERATED\n", 1)
out.write_text(f"{head}// BEGIN GENERATED\n{table}// END GENERATED\n{tail}")
